"""
2D Multimaterial Variational Assembler (VNMM)
==============================================
File: 2D/src/multimaterial_assembler_2d.py

Assembles global weak form stiffness K_curl, divergence penalty K_div,
and mass M matrices for isotropic or anisotropic media (including complex Hermitian tensors),
enforcing strict stencil support partition per material subdomain and Gauss numerical quadrature
over background Cartesian cells.
"""

import numpy as np
from scipy.spatial import KDTree
from scipy.sparse import csr_matrix
from scripts.support_nodes_vnmm_2d_6_p1 import support_nodes_vnmm_2d_6_p1
from src.gauss_quadrature_2d import get_gauss_points_weights_1d


def build_material_subsets(coords, vectors, mat_ids, shared_id=0):
    """
    Constructs spatial search subsets segregated by material index.
    Nodes with mat_id == shared_id (e.g. interface nodes) are visible to adjacent materials.
    """
    unique_mats = [m for m in np.unique(mat_ids) if m != shared_id]
    subsets = {}
    for m in unique_mats:
        cand = np.where((mat_ids == m) | (mat_ids == shared_id))[0]
        subsets[m] = {
            'indices': cand,
            'coords': coords[cand],
            'vectors': vectors[cand],
            'tree': KDTree(coords[cand])
        }
    return subsets


def assemble_multimaterial_matrices_2d(
    coords,
    vectors,
    subsets,
    mat_identifier_func,
    mat_properties_func,
    x_edges,
    y_edges,
    points_per_dir=2,
    domain_filter_func=None,
    K_stencil=12,
    tol_det=1e-5,
    dtype=float
):
    """
    Assembles global sparse matrices (K_curl, K_div, M) on multimaterial domains.

    Parameters:
    -----------
    coords: array (N, 2)
    vectors: array (N, 2)
    subsets: dict generated by build_material_subsets (or explicit quadrant map)
    mat_identifier_func: function (x, y) -> target_mat_id
    mat_properties_func: function (target_mat_id) -> (mu_r, eps_tensor)
    x_edges, y_edges: background grid boundaries
    domain_filter_func: optional function (x, y) -> bool (returns False outside domain)
    K_stencil: number of candidate nodes in local search
    tol_det: determinant threshold for support selection
    dtype: data type (float or complex)
    """
    total_nodes = len(coords)
    Ncx = len(x_edges) - 1
    Ncy = len(y_edges) - 1
    xi_1d, w_1d = get_gauss_points_weights_1d(points_per_dir)

    rows_Kc, cols_Kc, data_Kc = [], [], []
    rows_Kd, cols_Kd, data_Kd = [], [], []
    rows_M,  cols_M,  data_M  = [], [], []

    for j in range(Ncy):
        y0, y1 = y_edges[j], y_edges[j + 1]
        dy_c = y1 - y0
        yc = 0.5 * (y0 + y1)
        for i in range(Ncx):
            x0, x1 = x_edges[i], x_edges[i + 1]
            dx_c = x1 - x0
            xc = 0.5 * (x0 + x1)

            if domain_filter_func is not None and not domain_filter_func(xc, yc):
                continue

            det_J = 0.25 * dx_c * dy_c
            target_mat = mat_identifier_func(xc, yc)
            sub = subsets[target_mat]
            mu_r, eps_tensor = mat_properties_func(target_mat)

            if np.isscalar(eps_tensor):
                eps_mat = eps_tensor * np.eye(2, dtype=dtype)
            else:
                eps_mat = np.array(eps_tensor, dtype=dtype)

            inv_mu = 1.0 / mu_r

            for wi, xi in zip(w_1d, xi_1d):
                xg = xc + 0.5 * dx_c * xi
                for wj, eta in zip(w_1d, xi_1d):
                    yg = yc + 0.5 * dy_c * eta

                    if domain_filter_func is not None and not domain_filter_func(xg, yg):
                        continue

                    Pg = np.array([xg, yg])
                    wg = wi * wj * det_J

                    sel_local, det_A, matrix_A, eff_k = support_nodes_vnmm_2d_6_p1(
                        P=Pg,
                        nodes_coords=sub['coords'],
                        nodes_vectors=sub['vectors'],
                        search_tree=sub['tree'],
                        K=K_stencil,
                        Tol_det=tol_det,
                        adaptive=True
                    )
                    sel_global = sub['indices'][sel_local]

                    beta = np.linalg.inv(matrix_A)
                    Phi_g = beta[0:2, :]
                    rot_Phi = beta[4, :] - beta[3, :]
                    div_Phi = beta[2, :] + beta[5, :]

                    rot_outer = inv_mu * np.outer(rot_Phi, np.conj(rot_Phi)) * wg
                    div_outer = inv_mu * np.outer(div_Phi, np.conj(div_Phi)) * wg
                    vec_dot = (np.conj(Phi_g).T @ eps_mat @ Phi_g) * wg

                    for a in range(6):
                        Ia = sel_global[a]
                        for b in range(6):
                            Ib = sel_global[b]
                            rows_Kc.append(Ia); cols_Kc.append(Ib); data_Kc.append(rot_outer[a, b])
                            rows_Kd.append(Ia); cols_Kd.append(Ib); data_Kd.append(div_outer[a, b])
                            rows_M.append(Ia);  cols_M.append(Ib);  data_M.append(vec_dot[a, b])

    Kc = csr_matrix((data_Kc, (rows_Kc, cols_Kc)), shape=(total_nodes, total_nodes), dtype=dtype)
    Kd = csr_matrix((data_Kd, (rows_Kd, cols_Kd)), shape=(total_nodes, total_nodes), dtype=dtype)
    M  = csr_matrix((data_M,  (rows_M,  cols_M)),  shape=(total_nodes, total_nodes), dtype=dtype)

    return Kc, Kd, M
